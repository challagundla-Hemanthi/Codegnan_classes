#VARIABLE NAMES RULES IN PYTHON :

# RULE: A variable name must start with a letter or the underscore character
# RULE: A variable name cannot start with a number 
#  example: 2age is invalid, but age2 is valid or _age is valid


# RULE: A variable name can only contain alpha-numeric characters and underscores (A-z, 0-9, and _) 
# example: myvar, my_var, _my_var, myVar are valid variable names and in numaeric characters are not allowed in variable names
#legal variable names: age, Age, AGE, myage, my_age, myAge, _age, _my_age,my_age2, my2age, my2_age
#Illegal variable names: 2age, my-age, my.age, my age, my@age, my#age, my$age, my%age, my^age, my&age, my*age, my(age), my[age], my{age}, my|age, my\age, my/age, my?age, my!age

# RULE: Variable names are case-sensitive (age, Age and AGE are three different variables)


# RULE: Variable names should not be any of the Python keywords.
#like if, else, for, while, etc.
#example: if = 5 is invalid, but age = 5 is valid like------> if age = 5 is valid, but if = 5 is invalid

#MULTIWORD VARIABLE NAMES:
#RULE: Multiword variable names can be written in several ways:
    #Camel Case: myVariableName #this each word, except the first, starts with a capital letter
    #Pascal Case: MyVariableName #this each word starts with a capital letter
    #Snake Case: my_variable_name #this words are separated by underscores with no spaces and all letters are lowercase
    

